grapheme::value grapheme::scan(const std::string& grapheme_name)
{

    for (auto& [N,Str] : glyph_names)
    {
        if(grapheme_name == Str) return N;
    }
    return 0;
}

std::pair<bool, grapheme::value> grapheme::scan_name(const std::string& grapheme_name)
{
    for (auto& [N,Str] : glyph_names)
    {
        if(grapheme_name == Str) return {true, N};
    }
    return {false, 0};
}



std::string grapheme::name(grapheme::value gh)
{
    return glyph_names[gh];
}

std::string grapheme::text(grapheme::value gh) {
    return grapheme::db[gh];
}

